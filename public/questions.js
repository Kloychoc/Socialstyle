const PER = QUESTIONS.length / 2;          // 15 per axis
const LO = PER, HI = PER * 4, MID = (LO + HI) / 2; // 15..60, midpoint 37.5

function styleOf(a, r) {
  return a > MID ? (r > MID ? "expressive" : "driver") : (r > MID ? "amiable" : "analytical");
}

// answers: array of 1..4, one per question
function score(answers) {
  let a = 0, r = 0;
  QUESTIONS.forEach((q, i) => {
    const v = q.rev ? 5 - answers[i] : answers[i];
    if (q.ax === "A") a += v; else r += v;
  });
  return { a, r, style: styleOf(a, r) };
}

